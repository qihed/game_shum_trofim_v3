export function buildEnding(stats: Stats): EndingResult {
  const id = resolveEndingId(stats)
  const ending = ENDINGS[id]
  return {
    id,
    title: ending.title,
    tagline: ending.tagline,
    body: ending.body,
    statNotes: ending.statNotes,
  }
}

export function getAllEndingPreviews(): Array<{ id: EndingId; title: string; tagline: string }> {
  return ([1, 2, 3] as EndingId[]).map((id) => ({
    id,
    title: ENDINGS[id].title,
    tagline: ENDINGS[id].tagline,
  }))
}

export function formatStatNotes(stats: Stats, notes: Record<StatKey, string>): string {
  return (Object.keys(statLabels) as StatKey[])
    .map((key) => `${statLabels[key]}: ${stats[key]} — ${notes[key]}`)
    .join('\n\n')
}

