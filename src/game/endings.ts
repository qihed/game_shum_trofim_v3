export function sumStats(stats: Stats): number {
  return (Object.values(stats) as number[]).reduce((a, b) => a + b, 0)
}

function countKeyStatsAtOrBelow(stats: Stats, threshold: number): number {
  return KEY_STATS.filter((k) => stats[k] <= threshold).length
}

/** Правила из «финальные_концовки_игры_Максим.docx» */
export function resolveEndingId(stats: Stats): EndingId {
  const sum = sumStats(stats)
  const lowKeyCount = countKeyStatsAtOrBelow(stats, 3)

  if (sum <= 48 || lowKeyCount >= 2) {
    return 1
  }

  if (sum >= 73 && KEY_STATS.every((k) => stats[k] >= 6)) {
    return 3
  }

  if (sum >= 49 && sum <= 72) {
    return 2
  }

  if (lowKeyCount === 1 || sum >= 73) {
    return 2
  }

  if (stats.audienceContact < 6 || stats.projectViability < 6) {
    return sum <= 48 ? 1 : 2
  }

  return 2
}

